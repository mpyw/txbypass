package directive

import (
	"go/ast"
	"go/parser"
	"go/token"
	"slices"
	"testing"

	"github.com/mpyw/txbypass/internal/rule"
)

// scanSource parses src as file name, and scans its directives.
func scanSource(t *testing.T, name, src string) (*token.FileSet, *ast.File, *Set) {
	t.Helper()
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, name, src, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	read := func(string) ([]byte, error) { return []byte(src), nil }
	return fset, f, Scan(fset, []*ast.File{f}, read)
}

// lineStart is the position of the start of line in f.
func lineStart(fset *token.FileSet, f *ast.File, line int) token.Pos {
	return fset.File(f.Pos()).LineStart(line)
}

func allOn(rule.Name) bool { return true }

// A reason cannot be pinned by the analysistest fixtures: the expectation
// comment on a directive's line would be read as its reason.
func TestScanReason(t *testing.T) {
	const src = `package p

func f() {
	//txbypass:ignore
	_ = 0
	//txbypass:ignore //
	_ = 1
	//txbypass:ignore outer-handle
	_ = 2
	//txbypass:ignore // reason
	_ = 3
	//txbypass:ignore//reason
	_ = 4
}
`
	fset, f, s := scanSource(t, "p.go", src)
	var lines []int
	for _, p := range s.Problems() {
		if p.Message != "txbypass:ignore needs a reason after //" {
			t.Errorf("problem %q", p.Message)
		}
		lines = append(lines, fset.Position(p.Pos).Line)
	}
	if !slices.Equal(lines, []int{4, 6, 8}) {
		t.Errorf("problems on lines %v, want [4 6 8]", lines)
	}
	// An ignore without a reason silences nothing.
	for line, want := range map[int]bool{5: false, 7: false, 9: false, 11: true, 13: true} {
		if got := s.Ignored(lineStart(fset, f, line), rule.OuterHandle); got != want {
			t.Errorf("Ignored(line %d) = %v, want %v", line, got, want)
		}
	}
	if u := s.Unused(allOn); len(u) != 0 {
		t.Errorf("Unused() = %v, want none", u)
	}
}

func TestScanPlacement(t *testing.T) {
	const src = `package p

func f() {
	_ = 0 //txbypass:ignore outer-handle // trailing
	_ = 1
	//txbypass:ignore outer-handle // own line
	_ = 2
}
`
	fset, f, s := scanSource(t, "p.go", src)
	for line, want := range map[int]bool{4: true, 5: false, 6: false, 7: true} {
		if got := s.Ignored(lineStart(fset, f, line), rule.OuterHandle); got != want {
			t.Errorf("Ignored(line %d) = %v, want %v", line, got, want)
		}
	}
}

func TestUnusedWhenOff(t *testing.T) {
	const src = `package p

//txbypass:ignore outer-handle // the rule is off
func f() {}

//txbypass:ignore // names no rule, so no flag turns it off
func g() {}
`
	fset, _, s := scanSource(t, "p.go", src)
	off := func(rule.Name) bool { return false }
	if u := s.Unused(off); len(u) != 1 || fset.Position(u[0]).Line != 6 {
		t.Errorf("Unused() with the rule off = %v, want the ignore on line 6", u)
	}
	var lines []int
	for _, pos := range s.Unused(allOn) {
		lines = append(lines, fset.Position(pos).Line)
	}
	if !slices.Equal(lines, []int{3, 6}) {
		t.Errorf("unused on lines %v, want [3 6]", lines)
	}
}

func TestScanGenerated(t *testing.T) {
	const src = `// Code generated by hand. DO NOT EDIT.

package p

//txbypass:ignore
//txbypass:unknown
var _ = 0
`
	fset, f, s := scanSource(t, "gen.go", src)
	if len(s.Problems()) != 0 || len(s.Unused(allOn)) != 0 || s.Ignored(lineStart(fset, f, 7), rule.OuterHandle) {
		t.Errorf("a generated file was read: %v, %v", s.Problems(), s.Unused(allOn))
	}
}

// A file that cgo rewrote carries the generated marker, but its code and its
// directives are the user's.
func TestScanCgo(t *testing.T) {
	const src = `// Code generated by cmd/cgo; DO NOT EDIT.

package p

//txbypass:ignore // intended
var _ = 0
`
	fset, f, s := scanSource(t, "p.cgo1.go", src)
	if Generated(f) {
		t.Error("a file cgo rewrote counts as generated")
	}
	if !s.Ignored(lineStart(fset, f, 6), rule.OuterHandle) {
		t.Error("the directive in a file cgo rewrote was not read")
	}
}

